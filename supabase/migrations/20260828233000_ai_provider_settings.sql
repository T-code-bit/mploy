CREATE TABLE IF NOT EXISTS public.career_coach_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS career_coach_usage_user_created_idx
  ON public.career_coach_usage (user_id, created_at DESC);

ALTER TABLE public.career_coach_usage ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.career_coach_usage FROM anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.career_coach_usage TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.career_coach_usage_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.consume_career_coach_quota(
  p_user_id uuid,
  p_limit integer DEFAULT 20
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  recent_count integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));

  DELETE FROM public.career_coach_usage
  WHERE user_id = p_user_id
    AND created_at < now() - interval '1 hour';

  SELECT count(*) INTO recent_count
  FROM public.career_coach_usage
  WHERE user_id = p_user_id
    AND created_at >= now() - interval '1 hour';

  IF recent_count >= p_limit THEN
    RETURN false;
  END IF;

  INSERT INTO public.career_coach_usage (user_id) VALUES (p_user_id);
  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.consume_career_coach_quota(uuid, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_career_coach_quota(uuid, integer) TO service_role;